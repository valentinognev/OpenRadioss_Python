def _digest(table, of_qualnames=False):
    if of_qualnames:
        blob = "\n".join(sorted({v.__qualname__ for v in table.values()}))
    else:
        blob = "\n".join(f"{k}={table[k].__qualname__}" for k in sorted(table))
    return hashlib.sha256(blob.encode()).hexdigest()


