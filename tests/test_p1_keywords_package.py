def test_dispatch_resolves_through_its_key_fallbacks():
    """joined key -> first two parts -> bare key, then the engine-key bypass.

    The reader loop was copied verbatim into ``dispatch.py``; this drives
    each of its three lookups and its bypass list. A block that reaches a
    reader is never reported as "not ported", so the log is the observable
    that the same keyword still resolves to the same parser.
    """
    import pyradioss.input.keywords as K
    from pyradioss.common.messages import MessageLog
    from pyradioss.input.deck_reader import KeywordBlock

    def block(parts):
        return KeywordBlock(keyword="/".join(parts), parts=parts, user_id=None,
                            cards=[], source="test")

    # joined key "ALE_BCS"; two-part key "MAT_CRUSHABLE_FOAM" (the trailing
    # id is not part of the lookup); bare key "ACCEL" behind two unknown
    # parts; then the engine-only bypass and an unimplemented keyword.
    resolved = [["ALE", "BCS"], ["MAT", "CRUSHABLE_FOAM", "1"],
                ["ACCEL", "ZZZ", "7"]]
    blocks = [block(p) for p in resolved + [["H3D"], ["NOSUCHKEYWORD"]]]

    log = MessageLog()
    K.parse_starter_deck(blocks, log=log)
    text = "\n".join(log.messages)

    for parts in resolved + [["H3D"]]:
        assert f"/{'/'.join(parts)} not ported" not in text, (
            f"{'/'.join(parts)} stopped resolving to a reader"
        )
    assert "/NOSUCHKEYWORD not ported" in text, (
        "an unimplemented keyword must still be reported as not ported"
    )


