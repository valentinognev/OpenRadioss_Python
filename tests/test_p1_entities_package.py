# The nine submodules the split created.  Each appears in dir() of the package
# because Python binds an imported submodule as an attribute on its parent.
SUBMODULES = (
    "airbag",
    "constraints",
    "contact",
    "elements",
    "groups",
    "loads",
    "materials",
    "misc",
    "nodes",
)


def test_entities_is_a_package_not_a_file():
    import pyradioss.model.entities as E
    assert E.__path__, "entities must be a package so it can be split"


def test_public_export_list_is_unchanged():
    """No pre-split public name is dropped, and nothing new appears.

    Turning a module into a package unavoidably adds one public name per
    submodule: importing a submodule binds it as an attribute on its parent
    package, so dir() lists it.  That is a property of packages, not of this
    split, so the assertion is stated exactly rather than approximated -- the
    nine submodules are the whole of the permitted difference.
    """
    actual = {n for n in dir(_entities) if not n.startswith("_")}
    lost = sorted(set(EXPECTED_EXPORTS) - actual)
    assert lost == [], f"public names dropped by the split: {lost[:20]}"
    added = sorted(actual - set(EXPECTED_EXPORTS))
    assert added == sorted(SUBMODULES), (
        f"unexpected new public names: {added}"
    )


def test_package_re_exports_are_importable_by_the_same_path():
    """`from pyradioss.model.entities import Part` keeps working."""
    from pyradioss.model.entities import Part

    assert Part is getattr(_entities, "Part")
    assert isinstance(Part, type)


def test_every_expected_export_resolves_to_a_live_object():
    """No name may be a stale re-export: each must resolve in the package namespace."""
    missing = [n for n in EXPECTED_EXPORTS if not hasattr(_entities, n)]
    assert missing == [], f"names not resolvable: {missing[:10]}"
