def _bind_cross_module_references() -> None:
    """Publish every top-level name of each family module into its siblings.

    The readers were written when they all shared one module namespace, and
    the split did not rewrite a single call site, so a reader must still be
    able to resolve a sibling -- another reader, or a shared card constant
    like ``_IMP_DOF`` -- by bare name at call time. Some of those references
    are cyclic, which is why they cannot be plain module-level imports.
    """
    reserved = frozenset(
        ("__name__", "__doc__", "__file__", "__package__", "__loader__",
         "__spec__", "__builtins__", "__all__", "__path__", "__cached__"))
    registry = {}
    for module in _READER_MODULES:
        for name, obj in vars(module).items():
            if name not in reserved:
                registry[name] = obj
    for module in _READER_MODULES:
        namespace = module.__dict__
        for name, obj in registry.items():
            namespace.setdefault(name, obj)
    return None

_bind_cross_module_references()


