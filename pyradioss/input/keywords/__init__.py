"""
pyradioss.input.keywords - Starter keyword readers.

Split out of ``pyradioss/input/starter_keywords.py`` (Task P1.5). The public
surface is unchanged: ``parse_starter_deck``, ``read_starter_deck``,
``KEYWORD_PARSERS`` and every ``read_*`` reader are reachable from here, and
the old module path stays as a deprecation shim for one release cycle.

Layout
------
``dispatch.py``  keyword -> parser table and the block loop.
``geometry``, ``elements``, ``materials``, ``properties``, ``interfaces``,
``constraints``, ``loads``, ``conditions``, ``groups``, ``output``, ``misc``
                  the readers, one module per keyword family.

Cross-module references
-----------------------
The readers call each other freely - ``read_mat`` dispatches to the
``read_mat_law*`` readers, ``read_fail`` to the ``read_fail_*`` readers, and
so on - and some of those relationships are cyclic, so a reader module cannot
just ``from .materials import read_mat_law1`` at import time. Every family
module is therefore imported first and the readers are published into each
sibling module's globals once, by :func:`_bind_cross_module_references`. A
module-local definition always wins over a published one.
"""

